"""Read-only static inventory of a reference checkout. Never imports its code.

Usage: python tools/reference_inventory.py refs/Videl1 docs/REFERENCE_INVENTORY.md
This is a review index, not a vulnerability verdict or feature parity claim.
"""
import ast
import hashlib
import subprocess
import sys
from pathlib import Path


def inspect_file(path):
    raw = path.read_bytes()
    digest = hashlib.sha256(raw).hexdigest()[:12]
    try:
        tree = ast.parse(raw, filename=str(path))
    except (SyntaxError, ValueError) as error:
        return digest, [], [f'parse:{type(error).__name__} line {getattr(error, "lineno", "?")}']
    commands, flags = set(), set()
    for node in ast.walk(tree):
        if not isinstance(node, ast.Call):
            continue
        name = ast.unparse(node.func)
        leaf = name.rsplit('.', 1)[-1]
        if leaf in {'command', 'register', 'auth'}:
            values = [node.args[0]] if node.args else []
            values += [item.value for item in node.keywords if item.arg in {'commands', 'pattern'}]
            for value in values:
                if isinstance(value, ast.Constant) and isinstance(value.value, str):
                    commands.add(value.value)
                elif isinstance(value, (ast.List, ast.Tuple)):
                    commands.update(item.value for item in value.elts
                                    if isinstance(item, ast.Constant) and isinstance(item.value, str))
        if leaf in {'exec', 'eval', 'create_subprocess_shell', 'system', 'Popen',
                    'create_subprocess_exec', 'Client', 'AsyncGroq', 'AsyncOpenAI'}:
            flags.add(f'{name}:{node.lineno}')
    return digest, sorted(commands), sorted(flags)


def inventory(root):
    root = Path(root)
    files = sorted(path for path in root.rglob('*.py')
                   if not any(part in {'.git', '__pycache__', '.venv', 'venv'}
                              for part in path.relative_to(root).parts))
    try:
        revision = subprocess.check_output(['git', '-C', str(root), 'rev-parse', 'HEAD'], text=True).strip()
    except subprocess.CalledProcessError:
        revision = 'unknown'
    lines = ['# Reference static review index', '', f'Reference revision: `{revision}`.',
             f'Python files scanned: **{len(files)}**.', '',
             'Generated by `tools/reference_inventory.py`; no reference code is executed or copied.',
             'Command strings are literal candidates only: decorators may use regexes, aliases or',
             'dynamic expressions. Flags identify manual-review sites, not confirmed vulnerabilities.',
             '**Scanning every file is not a complete behavioral or security audit.**', '',
             '| Path | SHA256 prefix | Command candidates | Manual-review sites |',
             '| --- | --- | --- | --- |']
    for path in files:
        digest, commands, flags = inspect_file(path)
        def cell(value):
            return value.replace('|', '&#124;').replace('\n', ' ')
        lines.append(f'| `{path.relative_to(root)}` | `{digest}` | {cell(", ".join(commands))} | {cell(", ".join(flags))} |')
    return '\n'.join(lines) + '\n'


if __name__ == '__main__':
    Path(sys.argv[2]).write_text(inventory(sys.argv[1]))
