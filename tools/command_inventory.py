"""Reproducible source-declaration inventory; no Telegram connection or bot credentials."""
from pathlib import Path
import argparse
from agent.modules import MODULES
from agent.platform.menu import DESCRIPTIONS

BASE={'start':'Open bot / route private deep links','restart_bot':'Alias of start, not a process restart','help':'Available command help','h':'Alias of help','ping':'Bot responsiveness'}
POLISHED={'promote','demote','anonadmin','adminerror','admincache','adminlist','admins','resetwarns','pin','unpin','cleanservice','flood','setflood','setfloodtimer','floodmode','clearflood','etagall','eall','tagall','all','tagabort','allsettings','tagstats','tpromote','lang','cleancommand','keepcommand','modlog','antispam','approve','unapprove','approval','approved','note','warnings','warns','unwarn','rmwarn','resetwarn','resetallwarns','warn','kick','mute','unmute','ban','unban','rights','adminbox','privaterules','warntime','warnmode','fullpromote','admincount','setchatname','setchatphoto','setchatdescription','spurge','afk','userstats','recentactivity'}
MISSING=()


def inventory():
    rows=[(name,'shell','private',description) for name,description in BASE.items()]
    for module in MODULES:
        manifest=module.MANIFEST
        for name in manifest.commands:
            rows.append((name,manifest.slug,manifest.scope,DESCRIPTIONS.get(name,'Description missing')))
    names=[row[0] for row in rows]
    if len(names)!=len(set(names)):
        raise ValueError('Duplicate command declaration')
    return sorted(rows)


def render():
    rows=inventory()
    lines=['# Complete declared command inventory','',
           f'**{len(rows)} command names**, including shell aliases. Generated by `python -m tools.command_inventory`.',
           '', '## How to read this list', '',
           '- This lists source declarations, not proof of live Telegram/provider operation. No production bot was queried.',
           '- Scope is the manifest default; individual handlers and runtime policy may narrow it.',
           '- Plugin selection, worker/clone policy, premium/admin gates, credentials and capability checks determine availability.',
           '- Music is conditional on the assistant session/voice dependencies. Declared commands can be absent from a real build.',
           '- Use the deployed bot’s /help for its actual visible commands. Aliases are counted separately.',
           '- Reviewed below means targeted work/tests exist, not that all cards/controls/live paths are finished.', '',
           '## Every declared command', '', '| Command | Module | Default scope | Description | Review |',
           '|---|---|---|---|---|']
    for name,owner,scope,description in rows:
        description=description.replace('|',' / ').replace('\n',' ')
        state='Targeted review/tests' if name in POLISHED else 'Needs individual UI/behavior review'
        lines.append(f'| `/{name}` | {owner} | {scope} | {description} | {state} |')
    names={row[0] for row in rows}
    lines+=['','## Requested gaps (not fake registrations)','']
    if not MISSING:
        lines.append('- All originally requested command names are declared. This is not full feature parity or live verification.')
    for name in MISSING:
        if name not in names:
            lines.append(f'- `/{name}` — not implemented/registered.')
    lines+=['', '- Existing `/cancel` is not repurposed as mass-tag cancellation.',
            '- Tagging now retrieves up to 2000 returned group-member records and runs native jobs,20 mentions/message with5-second pauses and authorized Stop. No joining required; incomplete Telegram lists are disclosed.',
            '- Temporary promotion: /tpromote now has owner-only grants, durable deadlines, status/review resolution and a native expiry worker. Uncertain results stop for review; no blind retries.',
            '- Translation/free-provider and broadcast pin/cleanup parity remain incomplete; an existing declaration is not full upstream parity.', '',
            '## One-by-one improvement order', '',
            '1. Mute/unmute: rich cards, live rights, acknowledged actions and protected Unmute button implemented; live failure still needs runtime evidence.',
            '2. Ban/unban: shared target parsing, rich cards and exact acknowledgement in this phase. One-tap Unban control remains separate work.',
            '3. Kick: rich cards/shared targeting/live checks and acknowledged two-step recovery implemented. Base /warn now has a rich card and authorized View warnings control. Warning-removal cards now share one strict live-authorized path. New /warn cards include exact-warning removal controls; /warnings and /warns have self/admin access checks and live pagination.',
            '4. Timed promotion: owner-only /tpromote with durable admission, bounded expiry worker and status/manual-review resolution; no live-provider proof.',
            '5. Tagging family: retrieved-member snapshots, native jobs,20/5s batches, real Stop/Resume; no guarantee Telegram exposes everyone.',
            '6. Remaining declared commands: review module by module using this inventory; do not label untouched commands polished.', '']
    return '\n'.join(lines)


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output',default='docs/COMMAND_INVENTORY.md')
    args=parser.parse_args()
    path=Path(args.output)
    path.parent.mkdir(parents=True,exist_ok=True)
    path.write_text(render())


if __name__=='__main__':
    main()
